// ═══════════════════════════════════════════════════════════════════════════════
// Regenerates public/sitemap.xml from Sanity (runs automatically before
// `pnpm build`). Static pages are listed below; Programs, Retreats, Teachers and
// Blog posts come from Sanity's PUBLIC API (no token needed).
// If Sanity can't be reached, or a type has no documents yet, the existing
// sitemap entries for that type are kept — this script NEVER fails the build.
// ═══════════════════════════════════════════════════════════════════════════════
import fs from "fs";
import path from "path";

const SITE = "https://www.shivayoganiketan.com";
const PROJECT = "ntvvkd3p", DATASET = "production", API = "v2024-10-01";
const file = path.join(process.cwd(), "public/sitemap.xml");
const today = new Date().toISOString().slice(0, 10);

const STATIC = [
  ["/", "1.0", "weekly"], ["/programs", "0.9", "monthly"], ["/prices", "0.8", "monthly"],
  ["/appointment", "0.8", "monthly"], ["/retreats", "0.8", "monthly"], ["/about", "0.7", "yearly"],
  ["/teachers", "0.7", "monthly"], ["/contact", "0.7", "yearly"], ["/blog", "0.6", "weekly"],
  ["/sitemap", "0.3", "yearly"], ["/privacy", "0.2", "yearly"], ["/terms", "0.2", "yearly"],
];
const TYPES = [
  { type: "program", prefix: "/programs/", priority: "0.9", freq: "monthly" },
  { type: "retreat", prefix: "/retreats/", priority: "0.7", freq: "monthly" },
  { type: "teacher", prefix: "/teachers/", priority: "0.5", freq: "yearly" },
  { type: "post", prefix: "/blog/", priority: "0.5", freq: "yearly" },
];

// Existing entries (fallback per type).
const existing = fs.existsSync(file)
  ? [...fs.readFileSync(file, "utf8").matchAll(/<loc>([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g)].map((m) => ({ path: m[1].replace(SITE, "") || "/", lastmod: m[2] }))
  : [];

let cms = null;
try {
  const q = `{${TYPES.map((t) => `"${t.type}": *[_type == "${t.type}" && defined(slug.current)] | order(coalesce(order, 100) asc){ "slug": slug.current, "updated": _updatedAt }`).join(",")}}`;
  const url = `https://${PROJECT}.apicdn.sanity.io/${API}/data/query/${DATASET}?query=${encodeURIComponent(q)}&perspective=published`;
  const ctrl = new AbortController(); const t = setTimeout(() => ctrl.abort(), 10000);
  const res = await fetch(url, { signal: ctrl.signal }); clearTimeout(t);
  if (res.ok) cms = (await res.json()).result;
} catch (e) { console.warn("[sitemap] Sanity unreachable — keeping existing detail-page entries.", e.message); }

const entries = STATIC.map(([p, priority, freq]) => ({ path: p, lastmod: today, priority, freq }));
for (const t of TYPES) {
  const docs = cms?.[t.type];
  if (docs?.length) {
    for (const d of docs) entries.push({ path: t.prefix + d.slug, lastmod: String(d.updated).slice(0, 10), priority: t.priority, freq: t.freq });
  } else {
    for (const e of existing.filter((e) => e.path.startsWith(t.prefix))) entries.push({ ...e, priority: t.priority, freq: t.freq });
  }
}

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap.mjs on ${today}. Do not edit by hand — it is rebuilt from Sanity on every build. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries.map((e) => `  <url>\n    <loc>${SITE}${e.path === "/" ? "/" : e.path}</loc>\n    <lastmod>${e.lastmod}</lastmod>\n    <changefreq>${e.freq}</changefreq>\n    <priority>${e.priority}</priority>\n  </url>`).join("\n")}
</urlset>
`;
fs.writeFileSync(file, xml);
console.log(`[sitemap] ${entries.length} URLs written (${cms ? "from Sanity" : "Sanity offline — kept existing detail pages"}).`);
